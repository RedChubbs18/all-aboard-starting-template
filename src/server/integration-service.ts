export const DEFAULT_REMINDER_HOURS = 24;

/** FR-2.2. Reminder copy references First Advantage and the P&P contact. */
async function sendReminder(journey: JourneyState, status: string, message: string | undefined, ctx: ActorCtx): Promise<boolean> {
  const now = ctx.now ?? new Date();
  const detail = message ?? "Please complete your vetting steps.";
  const sent = await notifyUser(
    {
      toUserId: journey.starterId,
      journeyId: journey.id,
      kind: "PEV_REMINDER",
      subject: status === "action_needed" ? "Action needed on your First Advantage vetting" : "Reminder: finish your First Advantage vetting",
      body: `${detail} Stuck? Contact People & Places from the contact card on your journey.`,
      link: "/journey",
    },
    { ...ctx, now },
    "REMINDER_SENT",
  );
  return sent;
}

export interface ReminderOptions extends ActorCtx {
  /** Suppression window in hours. Default 24. */
  hours?: number;
  /** Ignore the suppression window (demo). */
  force?: boolean;
}

export interface ReminderResult {
  sent: { journeyId: string; starterId: string }[];
  suppressed: number;
  considered: number;
}

/**
 * Sends a reminder to each active PEV starter (or starter with First Advantage action needed/in progress before the offer stage)
 * whose First Advantage status is not cleared, unless they had one in the last `hours`. `now` is injectable for tests.
 */
export async function runReminders(now: Date = new Date(), opts: ReminderOptions = {}): Promise<ReminderResult> {
  const hours = opts.hours ?? DEFAULT_REMINDER_HOURS;
  const since = new Date(now.getTime() - hours * 3600_000);
  const journeys = await js.listJourneys({ status: "active" });
  const result: ReminderResult = { sent: [], suppressed: 0, considered: 0 };
  const hv = await getAdapter("firstadvantage");
  for (const j of journeys) {
    const vetting = await hv.getVettingStatus(j.id);
    if (vetting.status === "cleared") continue;
    const inPev = j.currentStage === "PEV";
    const early = stageIndex(j.currentStage) < stageIndex("UNCONDITIONAL_OFFER");
    if (!inPev && !(early && (vetting.status === "action_needed" || vetting.status === "in_progress"))) continue;
    result.considered++;
    if (!opts.force) {
      const last = await prisma.event.findFirst({ where: { journeyId: j.id, type: "REMINDER_SENT" }, orderBy: { createdAt: "desc" } });
      if (last && last.createdAt > since) {
        result.suppressed++;
        continue;
      }
    }
    if (await sendReminder(j, vetting.status, vetting.message, { actorId: opts.actorId, now })) {
      result.sent.push({ journeyId: j.id, starterId: j.starterId });
    }
  }
  return result;
}

