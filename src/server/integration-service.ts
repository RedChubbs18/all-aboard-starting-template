export interface AdapterView {
  key: AdapterKey;
  mode: AdapterMode;
  simulatable: boolean;
  statuses: readonly string[];
  status: string;
  updatedAt: string;
  detail?: string;
  facts: string[];
  error?: string;
}

async function facts(key: AdapterKey, journeyId: string): Promise<string[]> {
  switch (key) {
    case "identity": {
      const a = await (await getAdapter("identity")).getAccount(journeyId);
      return [`Conditional access: ${a.conditionalAccess}`, a.upn ? `Account: ${a.upn}` : "No internal account yet"];
    }
    case "sailpoint": {
      const a = await getAdapter("sailpoint");
      const [persona, fileId] = await Promise.all([a.getPersona(journeyId), a.getColleagueFileId(journeyId)]);
      return [persona ? `Persona: ${persona}` : "No persona applied", fileId ? `Colleague File ID: ${fileId.id}` : "No Colleague File ID yet"];
    }
    case "firstadvantage": {
      const v = await (await getAdapter("firstadvantage")).getVettingStatus(journeyId);
      return [`Provider: First Advantage`, `What is needed: ${v.message ?? "n/a"}`];
    }
    case "workday": {
      const a = await getAdapter("workday");
      const [days, training] = await Promise.all([a.getAnchorDays(journeyId), a.getTraining(journeyId)]);
      const done = training.filter((t) => t.status === "COMPLETE").length;
      return [`Anchor days: ${days.summary ?? days.days.join(" and ")}`, `Training: ${done} of ${training.length} complete`];
    }
    case "itrequest": {
      const a = await getAdapter("itrequest");
      const [can, list] = await Promise.all([a.canRaise(journeyId), a.list(journeyId)]);
      return [can.allowed ? "Requests unlocked" : `Locked: ${can.reason}`, `${list.length} request(s) raised`];
    }
    case "equipment": {
      const a = await getAdapter("equipment");
      const c = await a.getChoice(journeyId);
      return [c ? `${c.device}, ${c.peripherals.length} peripheral(s), collect at ${c.collectionPoint}` : "No device chosen"];
    }
    case "pass": {
      const o = await (await getAdapter("pass")).getOrder(journeyId);
      return [o ? `Order ${o.ref} to ${o.location}` : "No pass ordered"];
    }
    case "booking": {
      const a = await getAdapter("booking");
      const [b, sessions] = await Promise.all([a.getBooking(journeyId), a.listSessions()]);
      return [b ? `Booked: ${b.sessionId}` : "Not booked", `${sessions.length} sessions, ${sessions.reduce((n, s) => n + s.remaining, 0)} seats left`];
    }
    case "notification": {
      const list = await (await getAdapter("notification")).list({ journeyId });
      return [`${list.length} notification(s) for this journey`];
    }
    default:
      return [];
  }
}

export async function getSimulationView(journeyId: string) {
  const journey = await loadOrThrow(journeyId);
  const adapters: AdapterView[] = [];
  for (const key of ADAPTER_KEYS) {
    const mode = await getAdapterMode(key);
    try {
      const a = await getAdapter(key);
      const s = await a.getStatus(journeyId);
      adapters.push({
        key, mode, simulatable: isSimulatable(a), statuses: isSimulatable(a) ? a.simulatableStatuses : [],
        status: s.status, updatedAt: s.updatedAt, detail: s.detail, facts: await facts(key, journeyId).catch(() => []),
      });
    } catch (e) {
      adapters.push({ key, mode, simulatable: false, statuses: [], status: "unavailable", updatedAt: new Date(0).toISOString(), facts: [], error: e instanceof Error ? e.message : "error" });
    }
  }
  const events = (await js.listEvents(journeyId)).slice(-12).reverse();
  return {
    journey: { id: journey.id, starterId: journey.starterId, stage: journey.currentStage, flagged: journey.flagged, flagReason: journey.flagReason, status: journey.status },
    adapters,
    systemTasks: journey.tasks
      .filter((t) => t.owner === "SYSTEM" || t.adapterKey)
      .map((t) => ({ key: t.key, title: t.title, status: t.status, owner: t.owner, adapterKey: t.adapterKey })),
    events: events.map((e) => ({ id: e.id, type: e.type, entity: e.entity, entityId: e.entityId, to: e.to, at: e.createdAt })),
  };
}

