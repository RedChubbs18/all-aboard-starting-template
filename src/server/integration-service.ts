export class SimulationError extends Error {
  constructor(message: string, public status: 400 | 403 | 404 | 409 = 400) {
    super(message);
    this.name = "SimulationError";
  }
}

export interface ActorCtx {
  actorId?: string | null;
  now?: Date;
}

export interface SimulationResult {
  adapterKey: AdapterKey;
  journeyId: string;
  status: string;
  /** Human-readable list of what changed, for toasts and the event log. */
  changes: string[];
  stage: Stage;
  flagged: boolean;
}

// ------------------------------------------------------------------ helpers

const strArr = (v: unknown): string[] => (Array.isArray(v) ? v.map(String) : []);

const TERMINAL = new Set(["DONE"]);
const OPEN = new Set(["TODO", "IN_PROGRESS", "BLOCKED"]);

/** Send an in-app notification via the adapter and audit it. Returns false when notifications are unavailable (REAL, not configured). */
export async function notifyUser(input: NotificationInput, ctx: ActorCtx = {}, eventType = "NOTIFICATION_SENT"): Promise<boolean> {
  try {
    const sent = await (await getAdapter("notification")).send(input);
    await js.recordEvent({
      journeyId: input.journeyId ?? null,
      actorId: ctx.actorId ?? null,
      type: eventType,
      entity: "Notification",
      entityId: sent.id,
      data: { kind: input.kind, toUserId: input.toUserId },
      createdAt: ctx.now ?? new Date(),
    });
    return true;
  } catch (e) {
    if (e instanceof Error && e.name === "AdapterNotConfiguredError") return false;
    throw e;
  }
}

async function loadOrThrow(journeyId: string): Promise<JourneyState> {
  const j = await js.loadJourney(journeyId);
  if (!j) throw new SimulationError(`Journey ${journeyId} not found`, 404);
  return j;
}

function diff(before: JourneyState, after: JourneyState): string[] {
  const out: string[] = [];
  if (before.currentStage !== after.currentStage) out.push(`Stage moved from ${before.currentStage} to ${after.currentStage}`);
  if (!before.flagged && after.flagged) out.push(`Journey flagged${after.flagReason ? `: ${after.flagReason}` : ""}`);
  if (before.flagged && !after.flagged) out.push("Journey flag cleared");
  const prev = new Map(before.tasks.map((t) => [t.key, t.status]));
  for (const t of after.tasks) {
    const was = prev.get(t.key);
    if (was && was !== t.status) out.push(`Task "${t.title}": ${was} to ${t.status}`);
  }
  return out;
}

