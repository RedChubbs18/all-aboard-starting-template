/**
 * Integration service: the single bridge from adapter status changes to the journey.
 *
 *  - simulate(): update mock state, then apply it to the journey (engine via journey-service), audit-evented.
 *  - reconcileSystemTasks(): complete SYSTEM tasks whose external state already exists (account, persona, Colleague File ID).
 *  - runReminders(): FR-2.2 reminders. No timers: callers (the tick route) decide when to run it.
 *  - demo helpers for the /admin/simulate Demo script.
 *
 * Journey, task and event writes go through journey-service. The one exception is resetDemoStarter(),
 * which rebuilds a journey (it deletes and re-persists that journey's tasks via persistEngineResult) and, being
 * demo-only, also clears that journey's Day 0, goals, check-ins and events.
 */
