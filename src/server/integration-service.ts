/** Adapters whose simulated status only changes mock state (and reconciles SYSTEM tasks), never matching tasks by adapterKey. */
const STATE_ONLY: ReadonlySet<AdapterKey> = new Set(["identity", "sailpoint", "workday", "photocheck", "notification", "chatbot"]);

const STARTER_COPY: Partial<Record<string, { subject: string; body: string; kind: NotificationInput["kind"] }>> = {
  "identity:internal_created": { kind: "UPDATE", subject: "Your internal account is ready", body: "Your LBG account has been created with the pre-start access policy." },
  "sailpoint:file_id_created": { kind: "UPDATE", subject: "Your Colleague File ID is ready", body: "You can now raise your IT requests." },
  "firstadvantage:cleared": { kind: "UPDATE", subject: "Your vetting is cleared", body: "First Advantage has cleared your vetting. People & Places will confirm your offer conditions." },
};

/**
 * Simulate an external event for a journey, then apply it. Throws SimulationError for unknown or non-simulatable adapters.
 * `detail` is an optional plain-language message (e.g. what First Advantage needs).
 */
export async function simulate(
  adapterKey: AdapterKey,
  journeyId: string,
  status: string,
  detail?: string,
  ctx: ActorCtx = {},
): Promise<SimulationResult> {
  if (!(ADAPTER_KEYS as readonly string[]).includes(adapterKey)) throw new SimulationError(`Unknown adapter "${adapterKey}"`);
  const before = await loadOrThrow(journeyId);
  if (before.status !== "active") throw new SimulationError(`Journey is ${before.status}`, 409);

  const adapter = await getAdapter(adapterKey);
  if (!isSimulatable(adapter)) throw new SimulationError(`Adapter "${adapterKey}" cannot be simulated`, 409);
  if (!adapter.simulatableStatuses.includes(status)) {
    throw new SimulationError(`"${status}" is not a valid ${adapterKey} status (use ${adapter.simulatableStatuses.join(", ")})`);
  }
  await adapter.simulate(journeyId, status, detail);

  const changes: string[] = [];
  if (STATE_ONLY.has(adapterKey)) {
    await js.recordEvent({
      journeyId, actorId: ctx.actorId ?? null, type: "INTEGRATION_STATUS", entity: "Integration", entityId: adapterKey,
      to: status, data: { simulated: true }, createdAt: ctx.now ?? new Date(),
    });
  } else {
    const message = adapterKey === "firstadvantage" ? (await (await getAdapter("firstadvantage")).getVettingStatus(journeyId)).message : undefined;
    await js.applyIntegrationStatus(journeyId, adapterKey, status, { actorId: ctx.actorId ?? null, now: ctx.now, detail: detail ?? message });
  }

  const starterId = before.starterId;
  if (adapterKey === "firstadvantage" && status === "action_needed") {
    const hv = await (await getAdapter("firstadvantage")).getVettingStatus(journeyId);
    const sent = await sendReminder(before, "action_needed", hv.message, ctx);
    if (sent) changes.push("Reminder sent to the starter");
  } else {
    const copy = STARTER_COPY[`${adapterKey}:${status}`];
    if (copy && (await notifyUser({ toUserId: starterId, journeyId, link: "/journey", ...copy }, ctx))) changes.push("Starter notified");
  }

  const reconciled = await reconcileSystemTasks(journeyId, ctx);
  const after = await loadOrThrow(journeyId);
  changes.unshift(...diff(before, after));
  changes.push(...reconciled.filter((r) => !changes.includes(r)));
  const pending = after.tasks.filter((t) => t.status === "LOCKED" && t.applicable && SYSTEM_RULES.some((r) => r.taskKey === t.key));
  if (pending.length && STATE_ONLY.has(adapterKey)) {
    changes.push(`${pending.length} system task(s) still locked; they complete when earlier tasks are done`);
  }
  return { adapterKey, journeyId, status, changes, stage: after.currentStage, flagged: after.flagged };
}

